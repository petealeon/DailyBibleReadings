#!/usr/bin/env node
// Generates LectionaryCalendar.js (bundled liturgical calendar) from romcal.
//
// Usage:  cd tools && npm install && node generate-calendar.cjs
// Output: ../LectionaryCalendar.js  — one entry per date in the block.
//
// Rerun annually to extend the block (adjust YEARS below).

const fs = require("fs");
const path = require("path");
const romcal = require("romcal");

const YEARS = [2026, 2027, 2028, 2029, 2030];

const COLOUR_MAP = {
  GREEN: "green",
  WHITE: "white",
  GOLD: "white", // gold substitutes for white
  RED: "red",
  PURPLE: "violet",
  ROSE: "rose",
};

const iso = (moment) =>
  (moment instanceof Date ? moment : new Date(moment)).toISOString().slice(0, 10);

function main() {
  const days = {};
  for (const year of YEARS) {
    const cal = romcal.calendarFor({ year }, true);
    for (const d of cal) {
      const key = iso(d.moment);
      const colour = COLOUR_MAP[d.data.meta.liturgicalColor.key] || "green";
      const name = d.name;
      const saint = /^(saint|st\b|our lady|blessed virgin|the |ss\.)/i.test(name) &&
        d.type !== "FERIA" && d.type !== "SUNDAY" ? name : "";
      days[key] = {
        title: name,
        rank: d.type.toLowerCase(),
        colour: colour,
        saint: saint,
      };
    }
  }

  const keys = Object.keys(days).sort();
  const out = [
    "// Liturgical calendar " + keys[0] + " to " + keys[keys.length - 1] + ".",
    "// GENERATED by tools/generate-calendar.cjs (data: romcal, MIT) — do not edit by hand.",
    "// Rerun the generator annually to extend the block.",
    "",
    "var DAYS = " + JSON.stringify(days) + ";",
    "",
    "function get(key) {",
    "  return Object.prototype.hasOwnProperty.call(DAYS, key) ? DAYS[key] : null",
    "}",
    "",
    "function minDate() {",
    "  return " + JSON.stringify(keys[0]),
    "}",
    "",
    "function maxDate() {",
    "  return " + JSON.stringify(keys[keys.length - 1]),
    "}",
    "",
  ];

  const target = path.join(__dirname, "..", "LectionaryCalendar.js");
  fs.writeFileSync(target, out.join("\n"));
  console.log(
    "Wrote " + target + ": " + keys.length + " days, " +
    keys[0] + " .. " + keys[keys.length - 1] + ", " +
    Math.round(fs.statSync(target).size / 1024) + " KB"
  );
}

main();
